//go:build ignore

// This program is a local code generator for T070. It is excluded from normal
// builds via the "ignore" build tag and is executed by `go generate`.
//
// It regenerates day_string.go from the enum defined in day.go, mirroring what
// `stringer -type=Day` would emit. Run via: go generate ./...  then  go run .
package main

import (
	"bytes"
	"fmt"
	"os"
)

// enum values must stay in sync with day.go.
var days = []string{"Monday", "Tuesday", "Wednesday"}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_main.go; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("import \"fmt\"\n\n")
	fmt.Fprintf(&b, "var _dayNames = [...]string{\n")
	for i, name := range days {
		fmt.Fprintf(&b, "\t%d: %q,\n", i, name)
	}
	b.WriteString("}\n\n")
	b.WriteString("func (d Day) String() string {\n")
	b.WriteString("\tif d < 0 || int(d) >= len(_dayNames) {\n")
	b.WriteString("\t\treturn fmt.Sprintf(\"Day(%d)\", int(d))\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn _dayNames[d]\n")
	b.WriteString("}\n")

	if err := os.WriteFile("day_string.go", b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write failed:", err)
		os.Exit(1)
	}
	fmt.Println("generated day_string.go")
}
